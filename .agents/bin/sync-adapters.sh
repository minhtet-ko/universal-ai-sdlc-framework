#!/usr/bin/env bash
# sync-adapters.sh — generate per-tool adapters from the tool-neutral sources.
#
# Canonical (edit these):            Generated (never edit by hand):
#   AGENTS.md                          CLAUDE.md                      (Claude Code shim)
#   3-code/<component>/AGENTS.md       3-code/<component>/CLAUDE.md   (Claude Code shim)
#   .agents/skills/<name>/SKILL.md     .claude/skills/<name>/SKILL.md (Claude Code wrapper)
#                                      .gemini/commands/<name>.toml   (Gemini CLI /<name> command)
#                                      .gemini/settings.json          (created only if missing)
#
# Codex reads AGENTS.md and .agents/skills/ natively and needs no adapter.
# Gemini CLI also discovers .agents/skills/ natively; the commands add explicit /SDLC-* invocation.
#
# Usage:
#   .agents/bin/sync-adapters.sh           regenerate adapters in place (and prune stale ones)
#   .agents/bin/sync-adapters.sh --check   exit 1 if any adapter is missing, stale, or orphaned
#
# Run from anywhere inside the repository. Requires bash and standard POSIX tools.

set -euo pipefail

MARKER="Generated by .agents/bin/sync-adapters.sh"
MODE="write"
case "${1:-}" in
  "") ;;
  --check) MODE="check" ;;
  -h|--help) sed -n '2,19p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  *) echo "Unknown argument: $1 (use --check or --help)" >&2; exit 2 ;;
esac

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

# Build the full expected adapter set in a staging directory, then compare/apply.
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

shim_md() { # $1 = path of the canonical AGENTS.md relative to the shim
  printf '<!-- %s — do not edit. Canonical instructions: %s -->\n@%s\n' "$MARKER" "$1" "$1"
}

toml_escape() { # escape a value for a TOML basic (double-quoted) string
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# 1. Root Claude Code shim.
shim_md "AGENTS.md" > "$STAGE/CLAUDE.md"

# 2. Component Claude Code shims (one per 3-code/<component>/AGENTS.md).
for agents in 3-code/*/AGENTS.md; do
  [ -f "$agents" ] || continue
  dir="$(dirname "$agents")"
  mkdir -p "$STAGE/$dir"
  shim_md "AGENTS.md" > "$STAGE/$dir/CLAUDE.md"
done

# 3. Skill adapters.
for src in .agents/skills/*/SKILL.md; do
  [ -f "$src" ] || continue
  name="$(basename "$(dirname "$src")")"
  desc_line="$(sed -n '1,10p' "$src" | grep -m1 '^description:' || true)"
  if [ -z "$desc_line" ]; then
    echo "error: $src has no single-line 'description:' in its frontmatter" >&2
    exit 1
  fi
  desc="${desc_line#description: }"

  mkdir -p "$STAGE/.claude/skills/$name"
  cat > "$STAGE/.claude/skills/$name/SKILL.md" <<EOF
---
name: $name
$desc_line
---

<!-- $MARKER from .agents/skills/$name/SKILL.md — do not edit. -->

This skill is defined tool-neutrally in [\`.agents/skills/$name/SKILL.md\`](../../../.agents/skills/$name/SKILL.md).

Read that file in full now and follow its instructions exactly, as if they were written here. Relative links inside it (e.g. \`../shared/...\`) resolve from \`.agents/skills/$name/\`. Any context the user supplied together with this invocation is the skill's invocation context; no context means a bare invocation.
EOF

  mkdir -p "$STAGE/.gemini/commands"
  cat > "$STAGE/.gemini/commands/$name.toml" <<EOF
# $MARKER from .agents/skills/$name/SKILL.md — do not edit.
description = "$(toml_escape "$desc")"
prompt = """
Run the framework skill \`$name\`.

Read \`.agents/skills/$name/SKILL.md\` in full now and follow its instructions exactly, as if they were written here. Relative links inside it (e.g. \`../shared/...\`) resolve from \`.agents/skills/$name/\`.

Invocation context supplied by the user (empty means a bare invocation):
{{args}}
"""
EOF
done

# Gemini CLI settings: make it read AGENTS.md as its context file. Only created when
# missing, so per-project Gemini settings are never overwritten.
GEMINI_SETTINGS='{
  "context": {
    "fileName": ["AGENTS.md", "GEMINI.md"]
  }
}'

# --- Compare / apply -------------------------------------------------------------

problems=0
report() { echo "$1"; problems=$((problems + 1)); }

# Expected files.
while IFS= read -r rel; do
  if [ ! -f "$rel" ]; then
    if [ "$MODE" = check ]; then report "missing: $rel"; else
      mkdir -p "$(dirname "$rel")"; cp "$STAGE/$rel" "$rel"; echo "created: $rel"; fi
  elif ! cmp -s "$STAGE/$rel" "$rel"; then
    if [ "$MODE" = check ]; then report "stale:   $rel"; else
      cp "$STAGE/$rel" "$rel"; echo "updated: $rel"; fi
  fi
done < <(cd "$STAGE" && find . -type f | sed 's#^\./##' | sort)

if [ ! -f .gemini/settings.json ]; then
  if [ "$MODE" = check ]; then report "missing: .gemini/settings.json"; else
    mkdir -p .gemini; printf '%s\n' "$GEMINI_SETTINGS" > .gemini/settings.json; echo "created: .gemini/settings.json"; fi
fi

# Orphans: generated files (carrying the marker) whose source no longer exists.
while IFS= read -r rel; do
  [ -f "$STAGE/$rel" ] && continue
  grep -q "$MARKER" "$rel" 2>/dev/null || continue
  if [ "$MODE" = check ]; then report "orphan:  $rel"; else
    rm -f "$rel"; rmdir "$(dirname "$rel")" 2>/dev/null || true; echo "removed: $rel"; fi
done < <( { [ -f CLAUDE.md ] && echo CLAUDE.md;
            find 3-code -mindepth 2 -maxdepth 2 -name CLAUDE.md 2>/dev/null;
            find .claude/skills -name SKILL.md 2>/dev/null;
            find .gemini/commands -name '*.toml' 2>/dev/null; } | sort -u )

if [ "$MODE" = check ]; then
  if [ "$problems" -gt 0 ]; then
    echo "Adapters out of sync ($problems issue(s)). Run: .agents/bin/sync-adapters.sh" >&2
    exit 1
  fi
  echo "Adapters in sync."
fi
